_SPARK_TS_COLUMNS = ("source_updated_at", "deadline", "ingested_at")


def read_spark_silver(output_dir: str | Path) -> pl.DataFrame:
    """Read sharded Spark Silver Parquet, restoring UTC timestamp labels.

    Spark persists instants as UTC micros but the Parquet timezone label is
    lost, so Polars reads tz-naive columns. The UTC label is re-attached
    without shifting values; any genuine shift still fails parity on values.
    """

    frame = pl.read_parquet(str(Path(output_dir) / "part-*.parquet"))
    for column in _SPARK_TS_COLUMNS:
        dtype = frame.schema.get(column)
        if dtype is None:
            continue
        if getattr(dtype, "time_zone", None) is None:
            frame = frame.with_columns(
                pl.col(column).cast(pl.Datetime("us")).dt.replace_time_zone("UTC")
            )
        else:
            frame = frame.with_columns(pl.col(column).cast(pl.Datetime("us", "UTC")))
    return frame


def output_disk_usage(path: str | Path) -> tuple[int, int]:
    """Return ``(total_bytes, file_count)`` for a whole Silver artifact."""

    target = Path(path)
    if target.is_file():
        return target.stat().st_size, 1
    files = [entry for entry in target.rglob("*") if entry.is_file()]
    return sum(entry.stat().st_size for entry in files), len(files)


def output_parquet_usage(path: str | Path) -> tuple[int, int]:
    """Return ``(bytes, file_count)`` over ``*.parquet`` data files only.

    This is the comparable output figure across engines: sharded Spark
    directories also contain ``_SUCCESS``/checksum sidecars, which are
    reported separately as artifact totals by :func:`output_disk_usage`.
    """

    target = Path(path)
    if target.is_file():
        if target.suffix == ".parquet":
            return target.stat().st_size, 1
        return 0, 0
    files = [entry for entry in target.rglob("*.parquet") if entry.is_file()]
    return sum(entry.stat().st_size for entry in files), len(files)


def _tree_rss_psutil(pid: int) -> int | None:
    """Sum RSS over a process tree with psutil; None when the tree is gone."""

    import psutil

    try:
        root = psutil.Process(pid)
        total = root.memory_info().rss
    except (psutil.NoSuchProcess, psutil.AccessDenied):
        return None
    try:
        children = root.children(recursive=True)
    except (psutil.NoSuchProcess, psutil.AccessDenied):
        return total
    for child in children:
        try:
            total += child.memory_info().rss
        except (psutil.NoSuchProcess, psutil.AccessDenied):
            continue
    return total


def _proc_tree_pids(root: int) -> list[int]:
    """List a process and all descendants via /proc (Linux fallback)."""

    children: dict[int, list[int]] = {}
    pids: list[int] = []
    try:
        entries = os.listdir("/proc")
    except FileNotFoundError:
        return [root]
    for entry in entries:
        if not entry.isdigit():
            continue
        pid = int(entry)
        try:
            with open(f"/proc/{pid}/stat", encoding="utf-8") as handle:
                content = handle.read()
        except (FileNotFoundError, ProcessLookupError, PermissionError):
            continue
        try:
            rest = content[content.rindex(")") + 2 :].split()
            ppid = int(rest[1])
        except (ValueError, IndexError):
            continue
        children.setdefault(ppid, []).append(pid)
        pids.append(pid)
    seen = {root}
    queue = [root]
    while queue:
        current = queue.pop()
        for child in children.get(current, []):
            if child not in seen:
                seen.add(child)
                queue.append(child)
    return sorted(seen)


def _tree_rss_procfs(pid: int) -> int | None:
    """Sum RSS over a process tree via /proc; None when the tree is gone."""

    try:
        page_size = os.sysconf("SC_PAGE_SIZE")
    except (AttributeError, ValueError, OSError):
        page_size = 4096
    total = 0
    found = False
    for member in _proc_tree_pids(pid):
        try:
            with open(f"/proc/{member}/statm", encoding="utf-8") as handle:
                resident_pages = int(handle.read().split()[1])
        except (FileNotFoundError, ProcessLookupError, PermissionError, ValueError, IndexError):
            continue
        total += resident_pages * page_size
        found = True
    return total if found else None


class PeakSampler(threading.Thread):
    """Poll a process tree RSS in the background and retain the peak."""

    def __init__(self, pid: int, interval_s: float, method: str) -> None:
        super().__init__(daemon=True)
        self.pid = pid
        self.interval_s = interval_s
        self.method = method
        self.peak_bytes = 0
        self.samples = 0
        self._stop_event = threading.Event()

    def run(self) -> None:
        sample = _tree_rss_psutil if self.method == "psutil" else _tree_rss_procfs
        while not self._stop_event.is_set():
            try:
                value = sample(self.pid)
            except Exception:  # noqa: BLE001 - sampling must never kill the run
                value = None
            if value is not None:
                self.samples += 1
                self.peak_bytes = max(self.peak_bytes, value)
            time.sleep(self.interval_s)

    def stop(self) -> None:
        self._stop_event.set()


def rss_method() -> str:
    """Return the preferred available tree-RSS sampling method."""

    try:
        import psutil  # noqa: F401

        return "psutil"
    except ImportError:
        return "procfs"


def java_version() -> str | None:
    """Return the ``java -version`` line, used by the Spark engine only."""

    try:
        completed = subprocess.run(
            ["java", "-version"], capture_output=True, text=True, timeout=60
        )
    except (FileNotFoundError, OSError, subprocess.SubprocessError):
        return None
    output = (completed.stderr or completed.stdout or "").strip().splitlines()
    return output[0].strip() if output else None


def memory_total_bytes() -> int | None:
    """Return host RAM when discoverable without extra dependencies."""

    try:
        import psutil

        return int(psutil.virtual_memory().total)
    except ImportError:
        pass
    try:
        with open("/proc/meminfo", encoding="utf-8") as handle:
            for line in handle:
                if line.startswith("MemTotal:"):
                    return int(line.split()[1]) * 1024
    except (FileNotFoundError, OSError, ValueError, IndexError):
        pass
    return None


def _engine_worker(payload: dict[str, Any], queue: Any) -> None:
    """Run one engine measured stage in an isolated child process.

    ``engine_init_s`` covers engine-specific imports and, for Spark only,
    session creation. ``transform_s`` covers the identical
    read -> transform -> write boundary for every engine. Output rows are
    never counted here (the parent counts the written Parquet). Spark
    session stop and cache release are post-timer cleanup.
    """

    try:
        import time as _time

        engine = payload["engine"]
        init_started = _time.perf_counter()
        if engine == "python-row":
            import polars as _pl

            from .silver import build_procurement_events

            engine_init_s = _time.perf_counter() - init_started
            transform_started = _time.perf_counter()
            events = build_procurement_events(
                _pl.read_parquet(payload["records_glob"]),
                _pl.read_parquet(payload["tombstones_glob"]),
            )
            output = Path(payload["silver_path"])
            output.parent.mkdir(parents=True, exist_ok=True)
            events.write_parquet(output)
            report: dict[str, Any] = {
                "ok": True,
                "engine_init_s": engine_init_s,
                "transform_s": _time.perf_counter() - transform_started,
            }
        elif engine == "polars-native":
            import polars as _pl

            from .silver_polars import build_from_parquet

            engine_init_s = _time.perf_counter() - init_started
            transform_started = _time.perf_counter()
            events = build_from_parquet(payload["records_glob"], payload["tombstones_glob"])
            output = Path(payload["silver_path"])
            output.parent.mkdir(parents=True, exist_ok=True)
            events.write_parquet(output)
            report = {
                "ok": True,
                "engine_init_s": engine_init_s,
                "transform_s": _time.perf_counter() - transform_started,
            }
        elif engine == "spark-native":
            try:
                from .silver_spark import (
                    CACHE_STRATEGY,
                    build_session,
                    build_spark_events,
                    session_config_snapshot,
                    unpersist_frames,
                    write_silver_spark,
                )
            except ImportError as exc:
                from .silver_spark import INSTALL_HINT

                raise ImportError(f"PySpark is not installed. {INSTALL_HINT}") from exc
            import pyspark

            session = build_session(master=payload["spark_master"])
            spark_conf = session_config_snapshot(session)
            spark_version = session.version
            pyspark_version = pyspark.__version__
            engine_init_s = _time.perf_counter() - init_started
            transform_started = _time.perf_counter()
            frame, cached = build_spark_events(
                session, payload["records_glob"], payload["tombstones_glob"]
            )
            write_silver_spark(frame, payload["silver_path"])
            transform_s = _time.perf_counter() - transform_started
            unpersist_frames(cached)
            session.stop()
            report = {
                "ok": True,
                "engine_init_s": engine_init_s,
                "transform_s": transform_s,
                "spark_conf": spark_conf,
                "pyspark_version": pyspark_version,
                "spark_version": spark_version,
                "cache_strategy": CACHE_STRATEGY,
            }
        else:
            raise ValueError(f"Unknown engine {engine!r}")
        queue.put(report)
    except Exception as exc:  # noqa: BLE001 - transported back to the parent
        queue.put({"ok": False, "error_type": type(exc).__name__, "error": str(exc)})


def measure_engine(
    engine: str,
    records_glob: str,
    tombstones_glob: str,
    silver_path: str | Path,
    *,
    timeout_s: int = 3600,
    sample_interval_s: float = 0.02,
    spark_master: str | None = None,
) -> dict[str, Any]:
    """Measure one engine stage in an isolated child with tree-RSS sampling.

    Returns the child report plus parent-observed ``wall_s``,
    ``peak_tree_rss_bytes`` and the sampling method. A canonical material
    collision is re-raised as ``ValueError``; any other child failure
    becomes ``RuntimeError``.
    """

    method = rss_method()
    context = multiprocessing.get_context("spawn")
    queue = context.Queue()
    payload = {
        "engine": engine,
        "records_glob": records_glob,
        "tombstones_glob": tombstones_glob,
        "silver_path": str(silver_path),
        "spark_master": spark_master or f"local[{os.cpu_count() or 2}]",
    }
    process = context.Process(target=_engine_worker, args=(payload, queue))
    started = time.perf_counter()
    process.start()
    sampler = PeakSampler(process.pid or 0, sample_interval_s, method)
    sampler.start()
    try:
        process.join(timeout_s)
        wall_s = time.perf_counter() - started
        if process.is_alive():
            process.terminate()
            process.join()
            raise TimeoutError(f"measured stage for {engine} exceeded {timeout_s}s")
        try:
            report = queue.get(timeout=30)
        except QueueEmpty:
            raise RuntimeError(
                f"measured stage child for {engine} exited "
                f"with code {process.exitcode} without a report"
            ) from None
    finally:
        sampler.stop()
        sampler.join(timeout=10)
        queue.close()
        queue.join_thread()
    if not report.get("ok"):
        if report.get("error_type") == "ValueError":
            raise ValueError(report["error"])
        if report.get("error_type") == "ImportError":
            raise ImportError(report["error"])
        raise RuntimeError(f"{report.get('error_type')}: {report.get('error')}")
    report["wall_s"] = wall_s
    report["peak_tree_rss_bytes"] = sampler.peak_bytes
    report["rss_method"] = method
    report["rss_samples"] = sampler.samples
    report["rss_interval_s"] = sample_interval_s
    return report


def run_comparison(
    profile: str = "tiny",
    *,
    seed: int = 7,
    with_collision: bool = False,
    output: str | Path | None = None,
    work_dir: str | Path | None = None,
    engines: tuple[str, ...] | list[str] = ENGINE_ORDER,
    spark_master: str | None = None,
    sample_interval_s: float = 0.02,
) -> dict[str, Any]:
    """Run the offline engine comparison on one retained synthetic dataset.

    The dataset is generated once (timed separately, excluded) and every
    engine reads the same Bronze part files. With ``with_collision=True``
    every engine must raise the canonical material-collision ``ValueError``
    naming the same ``event_id``; no metrics are recorded.
    """

    unknown = [name for name in engines if name not in ENGINE_ORDER]
    if unknown:
        raise ValueError(f"Unknown engines {unknown!r}; expected a subset of {list(ENGINE_ORDER)}")
    params = dataset_profile(profile)
    if work_dir is None:
        import tempfile

        temporary = tempfile.TemporaryDirectory(prefix="bench-engines-")
        dataset_dir = Path(temporary.name)
        cleanup = temporary.cleanup
    else:
        temporary = None
        dataset_dir = Path(work_dir)
        dataset_dir.mkdir(parents=True, exist_ok=True)
        cleanup = None
    try:
        started_generation = time.perf_counter()
        manifest = write_bronze_parts(dataset_dir, seed=seed, with_collision=with_collision, **params)
        generation_s = time.perf_counter() - started_generation
        records_glob = str(dataset_dir / "records" / "part-*.parquet")
        tombstones_glob = str(dataset_dir / "tombstones" / "part-*.parquet")

        if with_collision:
            failures: dict[str, str] = {}
            for engine in engines:
                silver_path = dataset_dir / f"silver-{engine}" / "procurement_events.parquet"
                try:
                    measure_engine(
                        engine, records_glob, tombstones_glob, silver_path,
                        spark_master=spark_master, sample_interval_s=sample_interval_s,
                    )
                except ValueError as exc:
                    failures[engine] = str(exc)
                else:
                    raise AssertionError(f"engine {engine} did not fail on the collision dataset")
            tokens = {
                engine: set(
                    re.findall(r"(?:ted:notice|placsp:(?:notice|tombstone)):[^\s\]'\",]+", message)
                )
                for engine, message in failures.items()
            }
            common = set.intersection(*tokens.values()) if tokens else set()
            if not common:
                raise AssertionError(f"engines disagree on the collision event_id: {failures!r}")
            return {"with_collision": True, "failures": failures, "event_ids": sorted(common)}

        engine_metrics: dict[str, Any] = {}
        for engine in engines:
            silver_path = dataset_dir / f"silver-{engine}" / "procurement_events.parquet"
            report = measure_engine(
                engine, records_glob, tombstones_glob, silver_path,
                spark_master=spark_master, sample_interval_s=sample_interval_s,
            )
            parquet_bytes, parquet_files = output_parquet_usage(silver_path)
            artifact_bytes, artifact_files = output_disk_usage(silver_path)
            versions: dict[str, Any] = {
                "python_version": platform.python_version(),
                "polars_version": pl.__version__,
            }
            extra_conf: dict[str, Any] = {}
            if engine == "spark-native":
                versions["pyspark_version"] = report.pop("pyspark_version")
                versions["spark_version"] = report.pop("spark_version")
                versions["java_version"] = java_version()
                extra_conf["spark_conf"] = report.pop("spark_conf")
                extra_conf["spark_master"] = spark_master or f"local[{os.cpu_count() or 2}]"
                extra_conf["cache_strategy"] = report.pop("cache_strategy")
            else:
                extra_conf["cache_strategy"] = "not applicable (eager in-memory frame)"
            engine_metrics[engine] = {
                "implementation": engine,
                "implementation_detail": ENGINE_DETAILS[engine],
                "timing_s": {
                    "engine_init_s": report["engine_init_s"],
                    "transform_s": report["transform_s"],
                    "wall_s": report["wall_s"],
                },
                "throughput_rows_per_s": (
                    manifest["inputs"]["input_rows"] / report["transform_s"]
                    if report["transform_s"] > 0 else None
                ),
                "throughput_events_per_s": None,  # filled after parent-side count below
                "peak_tree_rss_bytes": report["peak_tree_rss_bytes"],
                "peak_tree_rss_scope": RSS_SCOPE,
                "rss_method": report["rss_method"],
                "rss_samples": report["rss_samples"],
                "rss_interval_s": report["rss_interval_s"],
                "inputs": {"input_rows": manifest["inputs"]["input_rows"]},
                "outputs": {
                    "silver_path": str(silver_path),
                    "silver_events": None,  # filled after parent-side count below
                    "parquet_bytes": parquet_bytes,
                    "parquet_files": parquet_files,
                    "artifact_bytes": artifact_bytes,
                    "artifact_files": artifact_files,
                },
                "versions": versions,
                **extra_conf,
            }

        started_validation = time.perf_counter()
        reference_path = dataset_dir / "silver-python-row" / "procurement_events.parquet"
        reference = pl.read_parquet(reference_path)
        parity: dict[str, Any] = {}
        for engine in engines:
            if engine == "python-row":
                candidate = reference
            elif engine == "spark-native":
                candidate = read_spark_silver(
                    dataset_dir / "silver-spark-native" / "procurement_events.parquet"
                )
            else:
                candidate = pl.read_parquet(
                    dataset_dir / f"silver-{engine}" / "procurement_events.parquet"
                )
            differences = compare_silver_frames(candidate, reference)
            parity[engine] = {"parity_ok": not differences, "differences": differences}
            engine_metrics[engine]["outputs"]["silver_events"] = candidate.height
            transform_s = engine_metrics[engine]["timing_s"]["transform_s"]
            engine_metrics[engine]["throughput_events_per_s"] = (
                candidate.height / transform_s if transform_s > 0 else None
            )
        validation_s = time.perf_counter() - started_validation
    finally:
        if cleanup is not None:
            cleanup()

    metrics: dict[str, Any] = {
        "benchmark": "bronze-parquet-to-silver-parquet-engines",
        "contract_scope": CONTRACT_SCOPE,
        "profile": profile,
        "profile_params": params,
        "seed": seed,
        "with_collision": with_collision,
        "dataset": {
            "dataset_dir": str(dataset_dir),
            **manifest["inputs"],
            "layout": manifest["layout"],
        },
        "stage": STAGE_DESCRIPTION,
        "timing_s": {"generation_s": generation_s},
        "engines": engine_metrics,
        "parity": {"reference": "python-row", "per_engine": parity},
        "validation_s": {
            "parity_and_counts_s": validation_s,
            "note": (
                "parent-side output loading, row counting and parity; "
                "excluded from the measured stage"
            ),
        },
        "hardware": {
            "platform": platform.platform(),
            "machine": platform.machine(),
            "cpu_count": os.cpu_count(),
            "memory_total_bytes": memory_total_bytes(),
        },
        "measured_at": datetime.now(UTC).isoformat(),
    }
    if output is not None:
        path = Path(output)
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(json.dumps(metrics, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    return metrics


def build_parser() -> argparse.ArgumentParser:
    """Build the engine-comparison CLI parser."""

    parser = argparse.ArgumentParser(
        description="Offline Bronze-Parquet-to-Silver-Parquet engine comparison "
        "(python-row vs polars-native vs spark-native)"
    )
    parser.add_argument("--profile", default="tiny", choices=sorted(PROFILES))
    parser.add_argument("--seed", default=7, type=int)
    parser.add_argument(
        "--with-collision", action="store_true",
        help="require every engine to fail with the same material-collision event_id",
    )
    parser.add_argument("--work-dir", default=None, type=Path)
    parser.add_argument("--output", default=None, type=Path)
    parser.add_argument(
        "--engines", default=",".join(ENGINE_ORDER),
        help=f"comma-separated subset of {','.join(ENGINE_ORDER)}",
    )
    parser.add_argument(
        "--spark-master", default=None,
        help="Spark master URL (default local[<cpu_count>])",
    )
    parser.add_argument(
        "--sample-interval-ms", default=20.0, type=float,
        help="parent RSS polling interval in milliseconds",
    )
    return parser


def main(argv: list[str] | None = None) -> int:
    """Execute the comparison and print the metrics JSON to stdout."""

    args = build_parser().parse_args(argv)
    metrics = run_comparison(
        args.profile, seed=args.seed, with_collision=args.with_collision,
        output=args.output, work_dir=args.work_dir,
        engines=tuple(part for part in args.engines.split(",") if part),
        spark_master=args.spark_master,
        sample_interval_s=args.sample_interval_ms / 1000.0,
    )
    print(json.dumps(metrics, ensure_ascii=False, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
