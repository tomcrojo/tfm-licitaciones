"""Offline comparison of Bronze-Parquet-to-Silver-Parquet engines (EXPERIMENT).

This module lives under ``experiments/`` and is NOT part of the production
pipeline: nothing under ``src/`` depends on it. It may import stable
production helpers (dataset generator, parity checks) from
:mod:`tfm_licitaciones`, but it MUST NOT import the mutable production
Silver facade (``tfm_licitaciones.silver``) for benchmark/reference
semantics: the ``python-row`` engine below is a frozen historical baseline,
not the current production implementation.

Compares, on the exact same retained synthetic dataset generated by
:mod:`tfm_licitaciones.bench_silver`:

- ``python-row``: the FROZEN historical ``build_procurement_events``
  baseline from commit ``e69016f`` (see
  :mod:`experiments.silver_engine_comparison.engines.python_row_reference`),
  per-row Python over a Polars/Parquet boundary;
- ``polars-native``: :mod:`experiments.silver_engine_comparison.engines.polars_candidate`
  (native Polars expressions/joins/grouping);
- ``spark-native``: :mod:`experiments.silver_engine_comparison.engines.spark_candidate`
  (native Spark SQL DataFrame execution; requires the optional pinned
  PySpark, never a base dependency).

SCOPE (loud limitation): the native candidates support only the
TED/PLACSP synthetic Bronze contract (see ``CONTRACT_SCOPE`` in each
engine module). Results from this harness are experiment evidence, not
production qualification.

Measurement definition (identical boundary for every engine, generation
excluded):

- the dataset is generated once into ``--work-dir`` (timed separately as
  ``generation_s``, excluded from the comparison);
- each engine then runs in a FRESH ``spawn`` child process, so every
  ``wall_s`` is cold and includes child startup (interpreter import; for
  Spark also JVM boot, session creation and post-write cleanup);
- inside the child, ``engine_init_s`` covers engine-specific imports and,
  for Spark only, session creation (the frozen python-row baseline needs
  no init beyond the child interpreter, same as the other non-Spark
  engine);
- ``transform_s`` starts immediately before the Bronze Parquet read and
  covers the same read -> canonical-transform -> Silver-Parquet-write
  boundary for all engines (for Spark it includes validation, collision
  and window jobs over persisted frames; session stop and unpersist are
  post-timer cleanup);
- output row counts are NOT measured in the child: the parent counts the
  written Parquet outputs (reusing the already-loaded parity frames) and
  times that parent-side loading/counting/parity work separately as
  ``validation_s``, explicitly outside the measured stage;
- ``peak_tree_rss_bytes`` is sampled by the PARENT while the child runs:
  the peak over time of the summed RSS of the child process plus ALL of
  its descendants (this includes the Spark JVM executors, unlike a
  child-only ``ru_maxrss``). Sampling polls every ``--sample-interval-ms``
  (default 20ms); spikes between samples can be missed, and the figure
  includes child/engine startup before the transform timer. The method
  (``psutil`` or Linux ``/proc`` fallback) is recorded per run;
- ``input_rows`` come from the dataset manifest; ``parquet_bytes``/
  ``parquet_files`` cover only ``*.parquet`` data files (comparable across
  engines) while ``artifact_bytes``/``artifact_files`` cover the whole
  written Silver artifact (for Spark this adds ``_SUCCESS``/checksums);
  ``coalesce(1)`` is never used;
- every engine writes Silver Parquet with the same pinned ``zstd`` codec
  (``PARQUET_CODEC``, matching ``spark_candidate.PARQUET_CODEC``): Spark's
  default would be snappy while Polars defaults to zstd, a ~5x
  output-size confound on identical logical content;
- Spark driver memory is set reproducibly via ``--spark-driver-memory``
  (applied as ``SPARK_DRIVER_MEMORY`` in the fresh child before JVM boot;
  setting ``spark.driver.memory`` after boot would not resize the heap)
  and the metrics record both the requested value and the actual JVM heap
  (``Runtime.getRuntime().maxMemory()``);
- parity of every engine against the frozen ``python-row`` reference is
  computed with :mod:`tfm_licitaciones.silver_parity` and stored in the
  metrics. The reference output is produced by the frozen experiment-local
  baseline
  (:mod:`experiments.silver_engine_comparison.engines.python_row_reference`),
  never by the mutable production Silver facade.

Spark Parquet interop note: Spark stores timestamps as UTC instants but
the Parquet files carry no timezone label, so Polars reads them back as
tz-naive. :func:`read_spark_silver` re-attaches the UTC label WITHOUT
shifting values (``replace_time_zone``, never ``convert_time_zone``);
value comparison still catches any real shift. Decimal(20,2), Date,
List(String) and strings round-trip exactly.
"""

